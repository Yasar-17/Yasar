import * as THREE from 'three';

// Exact proportional dimensions matching 372px x 806px display
export const PHONE_WIDTH = 3.72;
export const PHONE_HEIGHT = 8.06;
export const PHONE_DEPTH = 0.42;
export const CORNER_RADIUS = 0.46; // 48px equivalent radius

export function createRoundedRectShape(w, h, r) {
  const shape = new THREE.Shape();
  const x = -w / 2;
  const y = -h / 2;

  shape.moveTo(x + r, y);
  shape.lineTo(x + w - r, y);
  shape.quadraticCurveTo(x + w, y, x + w, y + r);
  shape.lineTo(x + w, y + h - r);
  shape.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  shape.lineTo(x + r, y + h);
  shape.quadraticCurveTo(x, y + h, x, y + h - r);
  shape.lineTo(x, y + r);
  shape.quadraticCurveTo(x, y, x + r, y);

  return shape;
}

